// ProofSight seller agent: x402-protected data-analysis endpoint.
// POST /analyze without payment -> 402 with requirements.
// POST /analyze with PAYMENT-SIGNATURE -> verify + settle via facilitator, then serve the report.
import http from 'node:http';
import fs from 'node:fs';
import crypto from 'node:crypto';
import * as ccd from '@concordium/web-sdk';
import { roleAccount, grpcClient, BADGE, NETWORK } from './accounts.mjs';

const seller = roleAccount('seller');
const FACILITATOR_URL = process.env.FACILITATOR_URL ?? 'http://localhost:8402';
const PRICE_MICRO_CCD = '1000000'; // 1 CCD
const AUDIT_FILE = new URL('../out/audit-log.json', import.meta.url).pathname;
const CARD_FILE = new URL('../agent-card.json', import.meta.url).pathname;

let audit = [];
try { audit = JSON.parse(fs.readFileSync(AUDIT_FILE, 'utf8')); } catch {}

function saveAudit() { fs.writeFileSync(AUDIT_FILE, JSON.stringify(audit, null, 1)); }

function paymentRequirements() {
    return {
        scheme: 'exact',
        network: NETWORK,
        amount: PRICE_MICRO_CCD,
        asset: 'CCD',
        payTo: seller.address,
        maxTimeoutSeconds: 120,
        extra: { feePayer: JSON.parse(fs.readFileSync(new URL('../out/account-facilitator.json', import.meta.url), 'utf8')).address },
    };
}

// --- the actual paid service: a deterministic data-analysis report ---
function analyze(dataset) {
    const series = (dataset?.series ?? DEMO_SERIES).map(Number).filter((x) => Number.isFinite(x));
    const n = series.length;
    const mean = series.reduce((a, b) => a + b, 0) / n;
    const sorted = [...series].sort((a, b) => a - b);
    const median = n % 2 ? sorted[(n - 1) / 2] : (sorted[n / 2 - 1] + sorted[n / 2]) / 2;
    const stdev = Math.sqrt(series.reduce((a, b) => a + (b - mean) ** 2, 0) / n);
    const min = sorted[0], max = sorted[n - 1];
    const first = series[0], last = series[n - 1];
    const changePct = first !== 0 ? ((last - first) / Math.abs(first)) * 100 : 0;
    const anomalies = series
        .map((v, i) => ({ i, v, z: stdev ? (v - mean) / stdev : 0 }))
        .filter((p) => Math.abs(p.z) > 2);
    const topic = dataset?.topic ?? 'Sample daily metric';
    return `# ProofSight analysis: ${topic}

- Data points: ${n}
- Mean: ${mean.toFixed(4)} | Median: ${median.toFixed(4)} | Stdev: ${stdev.toFixed(4)}
- Range: ${min} .. ${max}
- First -> last: ${first} -> ${last} (${changePct >= 0 ? '+' : ''}${changePct.toFixed(2)}%)
- Trend: ${changePct > 5 ? 'upward' : changePct < -5 ? 'downward' : 'flat'}
- Anomalies (|z| > 2): ${anomalies.length ? anomalies.map((a) => `#${a.i}=${a.v} (z=${a.z.toFixed(2)})`).join(', ') : 'none'}

Generated by ProofSight (badge ${BADGE}) on Concordium testnet.`;
}
const DEMO_SERIES = [42, 45, 44, 47, 46, 51, 49, 52, 55, 54, 58, 61, 59, 63, 66, 70, 68, 72, 75, 79];

const server = http.createServer(async (req, res) => {
    const send = (code, obj, headers = {}) => {
        const body = typeof obj === 'string' ? obj : JSON.stringify(obj, null, 1);
        res.writeHead(code, { 'content-type': typeof obj === 'string' && obj.startsWith('{') ? 'application/json' : 'application/json', ...headers });
        res.end(body);
    };
    const u = new URL(req.url, 'http://x');

    if (req.method === 'GET' && u.pathname === '/.well-known/agent-card.json') {
        res.writeHead(200, { 'content-type': 'application/json' });
        return res.end(fs.readFileSync(CARD_FILE));
    }
    if (req.method === 'GET' && u.pathname === '/api/audit') return send(200, audit);

    if (req.method === 'POST' && u.pathname === '/analyze') {
        let raw = '';
        for await (const c of req) raw += c;
        let reqBody = {};
        try { reqBody = raw ? JSON.parse(raw) : {}; } catch {}

        const requirements = paymentRequirements();
        const payHeader = req.headers['payment-signature'] ?? req.headers['x-payment'];
        if (!payHeader) {
            return send(402, {
                x402Version: 2,
                resource: { url: '/analyze', description: 'ProofSight data-analysis report', mimeType: 'text/markdown' },
                accepts: [requirements],
            });
        }

        let paymentPayload;
        try {
            paymentPayload = JSON.parse(Buffer.from(payHeader, 'base64').toString('utf8'));
        } catch {
            return send(402, { error: 'invalid payment header encoding', accepts: [requirements] });
        }
        if (!paymentPayload.payload) paymentPayload = { x402Version: 2, payload: paymentPayload };

        // verify
        const v = await fetch(`${FACILITATOR_URL}/verify`, {
            method: 'POST', headers: { 'content-type': 'application/json' },
            body: JSON.stringify({ paymentPayload, paymentRequirements: requirements }),
        }).then((r) => r.json());
        if (!v.isValid) return send(402, { error: `payment verification failed: ${v.invalidReason ?? JSON.stringify(v)}`, accepts: [requirements] });

        // settle
        const s = await fetch(`${FACILITATOR_URL}/settle`, {
            method: 'POST', headers: { 'content-type': 'application/json' },
            body: JSON.stringify({ paymentPayload, paymentRequirements: requirements }),
        }).then((r) => r.json());
        if (!s.success) return send(402, { error: `settlement failed: ${s.errorReason ?? JSON.stringify(s)}`, accepts: [requirements] });

        const report = analyze(reqBody.dataset);
        const reportHash = crypto.createHash('sha256').update(report).digest('hex');

        // anchor the report hash on-chain (EU AI Act style audit record), best effort
        let anchorTx = null;
        try {
            const client = grpcClient();
            const sender = ccd.AccountAddress.fromBase58(seller.address);
            const { nonce } = await client.getNextAccountNonce(sender);
            const anchorTxn = {
                header: { expiry: ccd.TransactionExpiry.fromDate(new Date(Date.now() + 3600000)), nonce, sender },
                payload: { data: new ccd.DataBlob(reportHash) },
                type: ccd.AccountTransactionType.RegisterData,
            };
            const sig = await ccd.signTransaction(anchorTxn, seller.signer);
            anchorTx = (await client.sendAccountTransaction(anchorTxn, sig)).toString();
            await client.waitForTransactionFinalization(ccd.TransactionHash.fromHexString(anchorTx));
        } catch (e) {
            console.error('anchor failed:', e.message);
        }

        const entry = {
            ts: new Date().toISOString(),
            sellerBadge: BADGE,
            payer: v.payer ?? null,
            amount_microCCD: PRICE_MICRO_CCD,
            txHash: s.transaction ?? s.txHash ?? null,
            network: NETWORK,
            explorer: `https://ccdexplorer.io/testnet/transaction/${s.transaction ?? s.txHash}`,
            badgeCheck: `https://agent-registry-mcp.concordium.com/v1/badge-check/${BADGE}`,
            reportSha256: reportHash,
            auditAnchorTx: anchorTx,
            auditAnchorExplorer: anchorTx ? `https://ccdexplorer.io/testnet/transaction/${anchorTx}` : null,
        };
        audit.push(entry);
        saveAudit();
        return send(200, { report, reportSha256: reportHash, settlement: entry }, { 'payment-response': Buffer.from(JSON.stringify(s)).toString('base64') });
    }
    send(404, { error: 'not found' });
});

const port = process.env.PORT ?? 3000;
server.listen(port, () => console.log(`ProofSight seller on :${port}, payTo ${seller.address}, facilitator ${FACILITATOR_URL}`));
